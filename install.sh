#!/bin/sh
set -eu

REPO="McNull/sshex"
INSTALL_DIR="${SSHEX_INSTALL_DIR:-$HOME/.local/bin}"
DATA_DIR="${SSHEX_HOME:-${XDG_DATA_HOME:-$HOME/.local/share}/sshex}"
COMPLETIONS_START="# >>> sshex completions >>>"
COMPLETIONS_END="# <<< sshex completions <<<"
COMPLETIONS_LINE_MARKER="sshex-completions-managed"

usage() {
	cat <<EOF
Usage: install.sh [VERSION]

Downloads and installs the sshex binary from GitHub releases.

Arguments:
  VERSION                 Release tag to install (e.g. v0.3.1). Defaults to latest.

Environment:
  SSHEX_INSTALL_DIR       Directory to install into. Defaults to \$HOME/.local/bin.
  SSHEX_VERSION           Same as the VERSION argument.
  SSHEX_NO_COMPLETIONS    Set to 1 to skip shell completion setup.

Examples:
  curl -fsSL https://raw.githubusercontent.com/${REPO}/main/install.sh | sh
  SSHEX_INSTALL_DIR="\$HOME/bin" ./install.sh v0.3.1
EOF
}

case "${1:-}" in
-h | --help)
	usage
	exit 0
	;;
esac

version="${1:-${SSHEX_VERSION:-}}"

if [ -n "$version" ]; then
	base_url="https://github.com/${REPO}/releases/download/${version}"
else
	base_url="https://github.com/${REPO}/releases/latest/download"
fi

# --- platform detection ---------------------------------------------------

os="$(uname -s | tr '[:upper:]' '[:lower:]')"
case "$(uname -m)" in
x86_64 | amd64) arch="amd64" ;;
aarch64 | arm64) arch="arm64" ;;
*)
	echo "sshex: unsupported architecture: $(uname -m)" >&2
	exit 1
	;;
esac

asset="sshex-${os}-${arch}.zip"
url="${base_url}/${asset}"

# --- dependencies ---------------------------------------------------------

if command -v curl >/dev/null 2>&1; then
	download() { curl -fL --progress-bar -o "$2" "$1"; }
elif command -v wget >/dev/null 2>&1; then
	download() { wget -q --show-progress -O "$2" "$1"; }
else
	echo "sshex: need either curl or wget to download releases" >&2
	exit 1
fi

if ! command -v unzip >/dev/null 2>&1; then
	echo "sshex: need 'unzip' to extract the release archive" >&2
	exit 1
fi

# --- shell completion helpers --------------------------------------------

detect_shell() {
	shell="${SHELL:-}"
	if [ -z "$shell" ] && command -v getent >/dev/null 2>&1; then
		shell="$(getent passwd "$(id -un)" 2>/dev/null | cut -d: -f7)"
	fi
	if [ -z "$shell" ] && command -v dscl >/dev/null 2>&1; then
		shell="$(dscl . -read "$HOME" UserShell 2>/dev/null | awk '{ print $2; exit }')"
	fi
	[ -n "$shell" ] || return 1
	basename "$shell"
}

remove_managed_block() {
	rc="$1"
	[ -f "$rc" ] || return 0
	tmp="${rc}.sshex-remove-completions.$$"
	if awk -v start="$COMPLETIONS_START" -v end="$COMPLETIONS_END" '
		$0 == start {
			if (inside) printf "%s", buffer
			inside = 1
			buffer = $0 ORS
			next
		}
		inside {
			buffer = buffer $0 ORS
			if ($0 == end) {
				inside = 0
				buffer = ""
			}
			next
		}
		{ print }
		END { if (inside) printf "%s", buffer }
	' "$rc" >"$tmp"; then
		mv "$tmp" "$rc"
	else
		rm -f "$tmp"
		return 1
	fi
}

install_managed_line() {
	rc="$1"
	line="$2"
	touch "$rc" || return 1
	tmp="${rc}.sshex-completions.$$"
	if SSHEX_LINE="$line" awk -v marker="$COMPLETIONS_LINE_MARKER" '
		index($0, marker) {
			if (!replaced) {
				print ENVIRON["SSHEX_LINE"]
				replaced = 1
			}
			next
		}
		{ print }
		END { if (!replaced) print ENVIRON["SSHEX_LINE"] }
	' "$rc" >"$tmp"; then
		mv "$tmp" "$rc"
	else
		rm -f "$tmp"
		return 1
	fi
}

write_shellrc() {
	shell="$1"
	shellrc="$2"
	{
		printf '%s\n' "# generated by sshex; do not edit"
		if [ "$shell" = zsh ]; then
			cat <<'EOF'
if ! typeset -f compdef >/dev/null 2>&1; then
	autoload -Uz compinit && compinit -i
fi
EOF
		fi
		printf 'if command -v sshex >/dev/null 2>&1; then\n\teval "$(sshex completions %s)"\nfi\n' "$shell"
	} >"$shellrc"
}

completion_source_line() {
	shell="$1"
	if [ "${DATA_DIR#"$HOME"/}" != "$DATA_DIR" ]; then
		rest="${DATA_DIR#"$HOME"/}"
		escaped_rest="$(printf '%s' "$rest" | sed 's/[\\"$`]/\\&/g')"
		printf '. "$HOME/%s/sshexrc.%s" # %s\n' "$escaped_rest" "$shell" "$COMPLETIONS_LINE_MARKER"
	else
		escaped_path="$(printf '%s' "$DATA_DIR" | sed 's/[\\"$`]/\\&/g')"
		printf '. "%s/sshexrc.%s" # %s\n' "$escaped_path" "$shell" "$COMPLETIONS_LINE_MARKER"
	fi
}

install_completions() {
	shell="$(detect_shell)" || return 0
	case "$shell" in
	bash | zsh | fish) ;;
	*)
		echo "Note: no shell completions for ${shell}; skipping." >&2
		return 0
		;;
	esac

	umask 077
	mkdir -p "$DATA_DIR" || return 0

	if [ "$shell" = fish ]; then
		mkdir -p "$DATA_DIR/completions" || return 0
		completion="$DATA_DIR/completions/sshex.fish"
		if ! "$INSTALL_DIR/sshex" completions fish >"$completion"; then
			echo "sshex: warning: could not generate fish completions" >&2
			rm -f "$completion"
			return 0
		fi
		fish_dir="${XDG_CONFIG_HOME:-$HOME/.config}/fish/completions"
		if mkdir -p "$fish_dir" && cp "$completion" "$fish_dir/sshex.fish"; then
			echo "Installed fish completions."
		else
			echo "sshex: warning: could not install fish completions" >&2
		fi
		return 0
	fi

	shellrc="$DATA_DIR/sshexrc.$shell"
	if ! write_shellrc "$shell" "$shellrc"; then
		echo "sshex: warning: could not write ${shellrc}" >&2
		return 0
	fi

	if [ "$shell" = zsh ]; then
		rc="${ZDOTDIR:-$HOME}/.zshrc"
	else
		rc="$HOME/.bashrc"
	fi

	remove_managed_block "$rc" || true
	line="$(completion_source_line "$shell")"
	if install_managed_line "$rc" "$line"; then
		echo "Installed ${shell} completions in ${rc}."
	else
		echo "sshex: warning: could not update ${rc} for completions" >&2
	fi
}

record_install_dir() {
	umask 077
	mkdir -p "$DATA_DIR" 2>/dev/null || return 0
	printf '%s\n' "$INSTALL_DIR" > "$DATA_DIR/install-dir" 2>/dev/null || true
}

# --- download -------------------------------------------------------------

tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT INT TERM

echo "Downloading ${asset} ..."
if ! download "$url" "$tmp/$asset"; then
	echo "sshex: no release available for ${os}/${arch} yet" >&2
	echo "sshex: tried ${url}" >&2
	exit 1
fi

if download "${base_url}/checksums.txt" "$tmp/checksums.txt" 2>/dev/null; then
	expected="$(awk -v a="$asset" '$2 == a { print $1 }' "$tmp/checksums.txt")"
	if [ -z "$expected" ]; then
		echo "sshex: checksum for ${asset} missing from checksums.txt" >&2
		exit 1
	fi
	actual="$(sha256sum "$tmp/$asset" | awk '{ print $1 }')"
	if [ "$actual" != "$expected" ]; then
		echo "sshex: checksum mismatch for ${asset}" >&2
		echo "  expected: ${expected}" >&2
		echo "  actual:   ${actual}" >&2
		exit 1
	fi
	echo "Checksum verified."
else
	echo "sshex: warning: could not download checksums.txt, skipping verification" >&2
fi

# --- extract and install --------------------------------------------------

unzip -q "$tmp/$asset" -d "$tmp"

if [ ! -f "$tmp/sshex" ]; then
	echo "sshex: ${asset} did not contain an sshex binary" >&2
	exit 1
fi

echo "Installing to ${INSTALL_DIR}/sshex ..."
if [ ! -d "$INSTALL_DIR" ]; then
	if [ -w "$(dirname "$INSTALL_DIR")" ] || [ "$(id -u)" -eq 0 ]; then
		mkdir -p "$INSTALL_DIR"
	else
		sudo mkdir -p "$INSTALL_DIR"
	fi
fi

if [ -w "$INSTALL_DIR" ] || [ "$(id -u)" -eq 0 ]; then
	install -m 0755 "$tmp/sshex" "$INSTALL_DIR/sshex"
elif command -v sudo >/dev/null 2>&1; then
	sudo install -m 0755 "$tmp/sshex" "$INSTALL_DIR/sshex"
else
	echo "sshex: ${INSTALL_DIR} is not writable and sudo is unavailable" >&2
	exit 1
fi

echo "Installed $("$INSTALL_DIR/sshex" --version 2>/dev/null || echo sshex)."

record_install_dir

if [ "${SSHEX_NO_COMPLETIONS:-}" = "1" ]; then
	echo "Skipping shell completions."
else
	install_completions
fi

if [ "$INSTALL_DIR" != "/usr/local/bin" ] && [ -x /usr/local/bin/sshex ]; then
	echo "Note: an older sshex exists at /usr/local/bin/sshex; remove it with: sudo rm /usr/local/bin/sshex" >&2
fi

case ":${PATH}:" in
*":${INSTALL_DIR}:"*) ;;
*) echo "Note: ${INSTALL_DIR} is not on your PATH." ;;
esac
